@login_required
def add_client_view(request):
    if request.method == 'POST':
        client_name = request.POST.get('client_name', '').strip()
        
        if not client_name:
            messages.error(request, 'Client name is required.')
            return render(request, 'new_client.html')
        
        # Create new client
        client = Client.objects.create(
            user=request.user,
            full_name=client_name
        )
        
        print(f"Created client: {client.full_name}")
        
        # Process uploaded files
        files = request.FILES.getlist('files')
        processed_files = []
        errors = []
        
        print(f"Processing {len(files)} files")
        
        for uploaded_file in files:
            try:
                print(f"Processing file: {uploaded_file.name}, type: {uploaded_file.content_type}")
                
                # Validate file type
                if not uploaded_file.content_type.startswith('image/'):
                    error_msg = f"File {uploaded_file.name} is not an image."
                    errors.append(error_msg)
                    print(error_msg)
                    continue
                
                # Read and encode the file
                uploaded_file.seek(0)  # Reset file pointer
                file_content = uploaded_file.read()
                print(f"File size: {len(file_content)} bytes")
                
                if len(file_content) == 0:
                    error_msg = f"File {uploaded_file.name} is empty."
                    errors.append(error_msg)
                    print(error_msg)
                    continue
                
                base64_image = base64.b64encode(file_content).decode('utf-8')
                print(f"Base64 encoded, length: {len(base64_image)}")
                
                # Extract text using Gemini API
                print("Calling extract_text_from_image...")
                try:
                    extracted_text = extract_text_from_image(base64_image, uploaded_file.content_type)
                    print(f"Extracted text: {extracted_text[:200]}...")
                except Exception as e:
                    print(f"Text extraction failed: {str(e)}")
                    extracted_text = f"Text extraction failed: {str(e)}"
                
                # Generate summary
                print("Generating summary...")
                try:
                    if extracted_text and not extracted_text.startswith("Error:") and not extracted_text.startswith("Text extraction failed:"):
                        summary = generate_summary(extracted_text)
                        print(f"Generated summary: {summary[:200]}...")
                    else:
                        summary = "No text found to summarize."
                        print("No valid text for summary")
                except Exception as e:
                    print(f"Summary generation failed: {str(e)}")
                    summary = f"Summary generation failed: {str(e)}"
                
                # Save file to database
                file_obj = File.objects.create(
                    client=client,
                    name=uploaded_file.name,
                    file_type=uploaded_file.content_type,
                    file_size=len(file_content),
                    extracted_text=extracted_text,
                    content=summary,  # Store summary in content field
                    processed=True
                )
                processed_files.append(file_obj)
                print(f"Saved file to database: {file_obj.id}")
                
            except Exception as e:
                error_msg = f"Error processing {uploaded_file.name}: {str(e)}"
                errors.append(error_msg)
                print(f"File processing error: {error_msg}")
        
        # Update client case summary with combined summaries
        if processed_files:
            try:
                summaries = []
                for f in processed_files:
                    if f.content and not f.content.startswith("Error:") and not f.content.startswith("Summary generation failed:"):
                        summaries.append(f.content)
                
                if summaries:
                    combined_summary = " | ".join(summaries)
                    # Truncate if too long
                    if len(combined_summary) > 1000:
                        combined_summary = combined_summary[:1000] + "..."
                    client.case_summary = combined_summary
                    client.save()
                    print(f"Updated client case summary: {combined_summary[:100]}...")
                else:
                    client.case_summary = "Files processed but no summaries could be generated."
                    client.save()
            except Exception as e:
                print(f"Error updating case summary: {str(e)}")
        
        # Show results to user
        if errors:
            for error in errors:
                messages.error(request, error)
        
        if processed_files:
            success_msg = f'Client "{client_name}" created successfully with {len(processed_files)} processed file(s).'
            messages.success(request, success_msg)
            print(success_msg)
            return redirect('existing_clients')
        else:
            error_msg = 'Client created but no files were successfully processed.'
            messages.error(request, error_msg)
            print(error_msg)
    
    return render(request, 'new_client.html')


