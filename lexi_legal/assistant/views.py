@csrf_exempt
@login_required
def process_file_api(request):
    if request.method == 'POST':
        try:
            client_id = request.POST.get('client_id')
            uploaded_file = request.FILES.get('file')

            print(f"API: Processing file for client {client_id}")

            if not uploaded_file:
                return JsonResponse({'success': False, 'error': 'No file uploaded.'}, status=400)

            if not uploaded_file.content_type.startswith('image/'):
                return JsonResponse({'success': False, 'error': 'Only image files are supported.'}, status=400)

            # Get the client object
            client = get_object_or_404(Client, id=client_id, user=request.user)

            # Read and encode the image
            uploaded_file.seek(0)  # Reset file pointer
            file_content = uploaded_file.read()
            
            if len(file_content) == 0:
                return JsonResponse({'success': False, 'error': 'Uploaded file is empty.'}, status=400)
                
            base64_image = base64.b64encode(file_content).decode('utf-8')

            print(f"API: File encoded, size: {len(file_content)} bytes")

            # Extract text using Gemini API
            try:
                extracted_text = extract_text_from_image(base64_image, uploaded_file.content_type)
                print(f"API: Text extracted: {extracted_text[:100]}...")
            except Exception as e:
                print(f"API: Text extraction error: {str(e)}")
                return JsonResponse({'success': False, 'error': f'Text extraction failed: {str(e)}'}, status=500)
            
            # Generate summary
            try:
                if extracted_text and not extracted_text.startswith("Error:"):
                    summary = generate_summary(extracted_text)
                    print(f"API: Summary generated: {summary[:100]}...")
                else:
                    summary = "No text found to summarize."
            except Exception as e:
                print(f"API: Summary generation error: {str(e)}")
                summary = f"Summary generation failed: {str(e)}"

            # Save file to database
            file_obj = File.objects.create(
                client=client,
                name=uploaded_file.name,
                file_type=uploaded_file.content_type,
                file_size=len(file_content),
                extracted_text=extracted_text,
                content=summary,
                processed=True
            )

            print(f"API: File saved to database: {file_obj.id}")

            return JsonResponse({
                'success': True,
                'file_id': file_obj.id,
                'extracted_text': extracted_text,
                'summary': summary
            })

        except Client.DoesNotExist:
            return JsonResponse({'success': False, 'error': 'Client not found.'}, status=404)
        except Exception as e:
            print(f"API: General error: {str(e)}")
            return JsonResponse({'success': False, 'error': f'Error processing file: {str(e)}'}, status=500)
   
    return JsonResponse({'success': False, 'error': 'Invalid request method.'}, status=405)




































