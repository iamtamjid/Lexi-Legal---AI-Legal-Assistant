# Helper functions for API calls
def call_gemini_api(request_body, use_vision=False):
    api_key = settings.GEMINI_API_KEY
    if not api_key:
        raise ValueError("API key not configured.")
   
    # Use different model for vision vs text tasks
    if use_vision:
        model = "gemini-1.5-flash"
    else:
        model = "gemini-1.5-flash"
    
    api_url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent?key={api_key}"
   
    headers = {
        'Content-Type': 'application/json'
    }
   
    try:
        print(f"Making API call to: {api_url}")
        print(f"Request body: {json.dumps(request_body, indent=2)}")
        
        response = requests.post(api_url, data=json.dumps(request_body), headers=headers)
        print(f"Response status: {response.status_code}")
        print(f"Response content: {response.text}")
        
        response.raise_for_status()
        data = response.json()
        
        if 'candidates' in data and len(data['candidates']) > 0:
            if 'content' in data['candidates'][0] and 'parts' in data['candidates'][0]['content']:
                text = data['candidates'][0]['content']['parts'][0]['text']
                return text
            else:
                print("Unexpected response structure")
                return "Error: Unexpected API response structure"
        else:
            print("No candidates in response")
            return "Error: No content generated by API"
            
    except requests.exceptions.RequestException as e:
        print(f"API Request Error: {e}")
        if hasattr(e, 'response') and e.response is not None:
            print(f"Error response: {e.response.text}")
        raise e
    except Exception as e:
        print(f"General API Error: {e}")
        raise e


def extract_text_from_image(base64_image, mime_type):
    """Extract text from image using Gemini Vision API"""
    request_body = {
        "contents": [{
            "parts": [
                {"text": "Extract all text, including handwritten text, from this image. Return only the extracted text without any additional formatting or commentary. If no text is found, return 'No text detected'."},
                {"inlineData": {"mimeType": mime_type, "data": base64_image}}
            ]
        }],
        "generationConfig": {
            "temperature": 0.1,
            "maxOutputTokens": 2048
        }
    }
    return call_gemini_api(request_body, use_vision=True)


def generate_summary(text):
    """Generate summary of extracted text"""
    if not text or text.strip() in ['', 'No text detected', 'No text found']:
        return "No text available to summarize"
        
    request_body = {
        "contents": [{
            "parts": [{"text": f"Create a concise legal document summary from the following text. Focus on key points, entities, dates, and legal implications. If the text is not legal-related, provide a general summary:\n\n{text}"}]
        }],
        "generationConfig": {
            "temperature": 0.3,
            "maxOutputTokens": 1024
        }
    }
    return call_gemini_api(request_body, use_vision=False)


def login_view(request):
    if request.user.is_authenticated:
        return redirect('dashboard')
    
    if request.method == 'POST':
        form = AuthenticationForm(request, data=request.POST)
        if form.is_valid():
            login(request, form.get_user())
            messages.success(request, 'Welcome back!')
            return redirect('dashboard')
        else:
            messages.error(request, 'Invalid username or password.')
    else:
        form = AuthenticationForm()
    return render(request, 'login.html', {'form': form})


def register_view(request):
    if request.user.is_authenticated:
        return redirect('dashboard')
        
    if request.method == 'POST':
        form = UserCreationForm(request.POST)
        if form.is_valid():
            user = form.save()
            login(request, user)
            messages.success(request, f'Welcome {user.username}! Your account has been created.')
            return redirect('dashboard')
        else:
            messages.error(request, 'Please correct the errors below.')
    else:
        form = UserCreationForm()
   
    return render(request, 'register.html', {'form': form})


